interface I18nContextValue {
  language: Language
  setLanguage: (value: Language) => void
  languages: LanguageOption[]
  t: (key: string, params?: Record<string, string>) => string
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined)

const LANGUAGE_STORAGE_KEY = 'portal.language'

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en')
  const [languages, setLanguages] = useState<LanguageOption[]>([
    { code: 'en', name: 'English', nativeName: 'English' }
  ])

  useEffect(() => {
    void (async () => {
      const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY) as Language | null
      if (stored && stored in TRANSLATIONS) {
        setLanguageState(stored)
      }

      try {
        const res = await fetch('/api/portal/language/default', { credentials: 'include' })
        if (!res.ok) return
        const data = await res.json() as { language?: Language; supportedLanguages?: LanguageOption[] }
        if (Array.isArray(data.supportedLanguages) && data.supportedLanguages.length > 0) {
          setLanguages(data.supportedLanguages)
        }

        if (!stored && data.language && data.language in TRANSLATIONS) {
          setLanguageState(data.language)
          window.localStorage.setItem(LANGUAGE_STORAGE_KEY, data.language)
        }
      } catch {
        // Keep defaults when lookup fails.
      }
    })()
  }, [])

  const setLanguage = (value: Language) => {
    setLanguageState(value)
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, value)
  }

  const t = useMemo(() => {
    return (key: string, params?: Record<string, string>) => {
      const template = TRANSLATIONS[language]?.[key] ?? TRANSLATIONS.en[key] ?? key
      if (!params) return template
      return Object.entries(params).reduce((text, [paramKey, paramValue]) => {
        return text.replace(`{${paramKey}}`, paramValue)
      }, template)
    }
  }, [language])

  return (
    <I18nContext.Provider value={{ language, setLanguage, languages, t }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) {
    throw new Error('useI18n must be used within LanguageProvider')
  }
  return context
}

export function formatPasswordExpirationWarning(t: I18nContextValue['t'], daysRemaining: number) {
  if (daysRemaining === 1) {
    return t('passwordExpiration.warningMessageOne')
  }
  return t('passwordExpiration.warningMessage', { days: String(daysRemaining) })
}
